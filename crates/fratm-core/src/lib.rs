/// Compilation options to customize the transpiler behavior.
///
/// # Example
///
/// ```rust
/// use fratm_core::CompileOptions;
///
/// let options = CompileOptions {
///     source_map: true,
///     filename: Some("main.fratm".to_string()),
///     minify: false,
///     jsx_import_source: None,
/// };
/// ```
#[derive(Debug, Clone, Default)]
pub struct CompileOptions {
    /// Generate source maps for debugging.
    ///
    /// When enabled, the compilation result will include a source map
    /// that maps the generated JavaScript to the original FratmScript code.
    pub source_map: bool,

    /// Source filename (used for source maps and error messages).
    ///
    /// If not specified, "input.fratm" is used as default.
    pub filename: Option<String>,

    /// Minify the JavaScript output (not yet implemented).
    ///
    /// When enabled, removes whitespace and shortens variable names.
    pub minify: bool,

    /// Library whose JSX runtime compiles JSX (`<source>/jsx-runtime`).
    ///
    /// `None` means `react`. A `// @jsxImportSource preact` comment in the
    /// file takes precedence.
    pub jsx_import_source: Option<String>,
}

/// Compilation result containing the generated code and metadata.
///
/// # Fields
///
/// * `code` - The generated JavaScript code
/// * `source_map` - Optional source map (if requested in options)
/// * `warnings` - List of non-fatal warnings generated during compilation
///
/// # Example
///
/// ```rust
/// use fratm_core::compile;
///
/// let result = compile("stamm a dì(42)", Default::default()).unwrap();
/// assert!(result.code.contains("console.log(42)"));
/// assert!(result.warnings.is_empty());
/// ```
#[derive(Debug, Clone)]
pub struct CompileResult {
    /// JavaScript code generated by the transpiler.
    pub code: String,

    /// Optional source map (present only if `source_map: true` in options).
    pub source_map: Option<SourceMap>,

    /// Non-fatal warnings generated during compilation.
    ///
    /// These are issues that don't prevent compilation but may
    /// indicate logical errors in the code.
    pub warnings: Vec<String>,
}

/// Compiles FratmScript code to JavaScript.
///
/// This is the main transpiler function. It takes source code
/// in Neapolitan syntax and produces equivalent JavaScript.
///
/// # Arguments
///
/// * `source` - The FratmScript source code to compile
/// * `options` - Compilation options (source maps, minification, etc.)
///
/// # Returns
///
/// * `Ok(CompileResult)` - Successful compilation with JS code
/// * `Err(CompileError)` - Compilation error with localized message
///
/// # Errors
///
/// This function can fail due to:
/// * Lexical errors (unclosed strings, invalid characters)
/// * Syntax errors (missing parentheses, wrong keywords)
///
/// # Example
///
/// ```rust
/// use fratm_core::{compile, CompileOptions};
///
/// // Simple compilation
/// let result = compile("chist è x = 42", Default::default()).unwrap();
/// assert!(result.code.contains("const x = 42"));
///
/// // With source map
/// let options = CompileOptions { source_map: true, ..Default::default() };
/// let result = compile("chist è x = 42", options).unwrap();
/// assert!(result.source_map.is_some());
/// ```
///
/// # Compilation Pipeline
///
/// ```text
/// Source Code → Lexer → Tokens → Parser → AST → CodeGen → JavaScript
/// ```
pub fn compile(source: &str, options: CompileOptions) -> Result<CompileResult, CompileError> {
    // Lexing
    let mut lexer = Lexer::new(source);
    let tokens = lexer.tokenize();

    // Check for lexer errors, including inside template interpolations
    if let Some(t) = first_invalid(&tokens) {
        if let lexer::TokenKind::Invalid(msg) = &t.kind {
            return Err(CompileError::LexerError {
                message: msg.clone(),
                line: t.span.line,
                column: t.span.column,
            });
        }
    }

    // Parsing
    let mut parser = Parser::new(tokens.clone());
    let program = parser.parse().map_err(|errors| {
        let first = errors.into_iter().next().unwrap();
        CompileError::ParseError {
            message: first.message,
            line: first.span.line,
            column: first.span.column,
        }
    })?;

    // Semantic checks
    checker::check(&program).map_err(|e| CompileError::SemanticError {
        message: e.message,
        line: e.span.line,
        column: e.span.column,
    })?;

    // Code generation
    let mut codegen = CodeGen::new(options.source_map);
    if let Some(line) = shebang(source) {
        codegen.emit_shebang(line);
    }
    if uses_jsx(&tokens) {
        let source = jsx_import_source(source)
            .or(options.jsx_import_source.as_deref())
            .unwrap_or(DEFAULT_JSX_IMPORT_SOURCE);
        codegen.emit_jsx_import(source);
    }
    let code = codegen.generate(&program);

    let source_map = if options.source_map {
        Some(codegen.get_source_map())
    } else {
        None
    };

    Ok(CompileResult {
        code,
        source_map,
        warnings: vec![],
    })
}

/// The `#!` line at the very start of `source`, if any (without the newline).
pub(crate) fn shebang(source: &str) -> Option<&str> {
    if !source.starts_with("#!") {
        return None;
    }
    let line = source.lines().next().unwrap_or(source);
    Some(line.strip_suffix('\r').unwrap_or(line))
}

fn first_invalid(tokens: &[lexer::Token]) -> Option<&lexer::Token> {
    tokens.iter().find_map(|t| match &t.kind {
        lexer::TokenKind::Invalid(_) => Some(t),
        lexer::TokenKind::Template { expressions, .. } => {
            expressions.iter().find_map(|e| first_invalid(e))
        }
        lexer::TokenKind::Jsx(element) => {
            jsx_token_lists(element).into_iter().find_map(first_invalid)
        }
        _ => None,
    })
}

/// JSX compiles to calls into `react/jsx-runtime` unless told otherwise.
pub const DEFAULT_JSX_IMPORT_SOURCE: &str = "react";

/// Whether the program has JSX anywhere, also inside template interpolations.
fn uses_jsx(tokens: &[lexer::Token]) -> bool {
    tokens.iter().any(|t| match &t.kind {
        lexer::TokenKind::Jsx(_) => true,
        lexer::TokenKind::Template { expressions, .. } => expressions.iter().any(|e| uses_jsx(e)),
        _ => false,
    })
}

/// The token lists of every `{ … }` in a JSX element, nested ones included.
fn jsx_token_lists(element: &lexer::JsxToken) -> Vec<&[lexer::Token]> {
    use lexer::{JsxTokenAttribute, JsxTokenChild, JsxTokenValue};
    let mut lists = Vec::new();
    for attribute in &element.attributes {
        match attribute {
            JsxTokenAttribute::Spread(tokens)
            | JsxTokenAttribute::Named {
                value: Some(JsxTokenValue::Expression(tokens)),
                ..
            } => lists.push(tokens.as_slice()),
            JsxTokenAttribute::Named {
                value: Some(JsxTokenValue::Element(nested)),
                ..
            } => lists.extend(jsx_token_lists(nested)),
            JsxTokenAttribute::Named { .. } => {}
        }
    }
    for child in element.children.iter().flatten() {
        match child {
            JsxTokenChild::Expression(tokens, _) => lists.push(tokens.as_slice()),
            JsxTokenChild::Element(nested) => lists.extend(jsx_token_lists(nested)),
            JsxTokenChild::Text(_) => {}
        }
    }
    lists
}

/// The library named by a `@jsxImportSource preact` comment, as in Babel
/// and TypeScript.
fn jsx_import_source(source: &str) -> Option<&str> {
    source.lines().find_map(|line| {
        let line = line.trim_start();
        if !(line.starts_with("//") || line.starts_with("/*") || line.starts_with('*')) {
            return None;
        }
        let (_, rest) = line.split_once("@jsxImportSource")?;
        rest.split_whitespace()
            .next()
            .map(|name| name.trim_end_matches("*/"))
            .filter(|name| !name.is_empty())
    })
}

